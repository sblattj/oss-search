use std::io;
use std::path::{Path, PathBuf};

use serde::Serialize;

use crate::code_eval::{CodeEvalReport, DEPTH, K};
use crate::latency::LatencyReport;
use crate::repo_eval::RepoEvalReport;

pub const EVAL_MD: &str = "EVAL.md";

pub fn write_json<T: Serialize>(dir: &Path, name: &str, value: &T) -> io::Result<()> {
    let json = serde_json::to_string_pretty(value)?;
    std::fs::write(dir.join(name), json)?;
    Ok(())
}

pub fn md_table(headers: &[&str], rows: &[Vec<String>]) -> String {
    let mut out = String::new();
    out.push_str("| ");
    out.push_str(&headers.join(" | "));
    out.push_str(" |\n");
    out.push('|');
    for _ in headers {
        out.push_str(" --- |");
    }
    out.push('\n');
    for row in rows {
        out.push_str("| ");
        out.push_str(&row.join(" | "));
        out.push_str(" |\n");
    }
    out
}

fn fmt(v: f64) -> String {
    format!("{v:.4}")
}

pub fn write_eval_md(
    dir: &Path,
    code: &CodeEvalReport,
    repo: &RepoEvalReport,
    latency: &LatencyReport,
) -> io::Result<PathBuf> {
    let mut md = String::new();
    md.push_str("# EVAL\n\n");

    md.push_str(&format!(
        "## Code search golden set ({} queries over {} docs)\n\n",
        code.queries, code.corpus_docs
    ));
    md.push_str(&md_table(
        &["metric", "value"],
        &[
            vec!["ndcg@10".into(), fmt(code.ndcg_at_10)],
            vec!["mrr".into(), fmt(code.mrr)],
            vec![format!("recall@{DEPTH}"), fmt(code.recall_at_50)],
        ],
    ));
    md.push('\n');
    let rows: Vec<Vec<String>> = code
        .per_query
        .iter()
        .map(|m| {
            vec![
                m.query_id.clone(),
                m.kind.clone(),
                m.text.clone(),
                fmt(m.ndcg_at_10),
                fmt(m.reciprocal_rank),
                fmt(m.recall_at_50),
                m.judged_relevant.to_string(),
                m.relevant_returned.to_string(),
            ]
        })
        .collect();
    md.push_str(&md_table(
        &[
            "query",
            "kind",
            "text",
            "ndcg@10",
            "rr",
            "recall@50",
            "judged",
            "hits",
        ],
        &rows,
    ));
    md.push('\n');

    md.push_str(&format!(
        "## Repo discovery (awesome-list ground truth, hit_rate@{} over {} topics)\n\n",
        repo.eval.k, repo.eval.topics
    ));
    md.push_str(&md_table(
        &["metric", "value"],
        &[
            vec![
                format!("hit_rate@{}", repo.eval.k),
                fmt(repo.eval.hit_rate_at_k),
            ],
            vec!["mrr".into(), fmt(repo.eval.mrr)],
        ],
    ));
    md.push('\n');
    let topic_rows: Vec<Vec<String>> = repo
        .eval
        .per_topic
        .iter()
        .map(|t| {
            vec![
                t.topic.clone(),
                t.hit_at_k.to_string(),
                t.first_hit_rank.map_or("-".into(), |r| r.to_string()),
                fmt(t.reciprocal_rank),
            ]
        })
        .collect();
    md.push_str(&md_table(
        &["topic", "hit@k", "first_hit_rank", "rr"],
        &topic_rows,
    ));
    md.push('\n');
    let decoy_rows: Vec<Vec<String>> = repo
        .decoy_ranks
        .iter()
        .map(|d| vec![d.topic.clone(), d.repo_url.clone(), d.rank.to_string()])
        .collect();
    md.push_str("### Decoy (negative control) ranks\n\n");
    md.push_str(&md_table(&["topic", "decoy", "rank"], &decoy_rows));
    md.push('\n');

    md.push_str(&format!(
        "## Latency ({} queries over {} docs, microseconds)\n\n",
        latency.queries, latency.docs
    ));
    md.push_str(&md_table(
        &["p50_us", "p90_us", "p99_us", "max_us", "mean_us"],
        &[vec![
            latency.p50_us.to_string(),
            latency.p90_us.to_string(),
            latency.p99_us.to_string(),
            latency.max_us.to_string(),
            format!("{:.1}", latency.mean_us),
        ]],
    ));
    md.push('\n');
    let mut slowest: Vec<&crate::latency::LatencyRow> = latency.per_query.iter().collect();
    slowest.sort_by_key(|r| std::cmp::Reverse(r.micros));
    let slow_rows: Vec<Vec<String>> = slowest
        .iter()
        .take(5)
        .map(|r| vec![r.query.clone(), r.micros.to_string()])
        .collect();
    md.push_str("### Slowest queries\n\n");
    md.push_str(&md_table(&["query", "micros"], &slow_rows));
    md.push('\n');
    md.push_str(&format!(
        "Report generated by oss-eval; depth {DEPTH}, k {K}.\n"
    ));

    let path = dir.join(EVAL_MD);
    std::fs::write(&path, md)?;
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn md_table_renders_header_separator_and_rows() {
        let t = md_table(&["a", "b"], &[vec!["1".into(), "2".into()]]);
        assert!(t.starts_with("| a | b |\n| --- | --- |\n"));
        assert!(t.contains("| 1 | 2 |\n"));
    }
}
